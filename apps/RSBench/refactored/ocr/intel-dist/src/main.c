ocrGuid_t FNC_globalComputeSpawner(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    u32 _paramc, _depc, _idep;

    ocrGuid_t DBK_InputsH = depv[0].guid;
    ocrGuid_t DBK_dataH = depv[1].guid;
    ocrGuid_t DBK_templatesH = depv[2].guid;

    ocrGuid_t* PTR_psumGuids = depv[3].ptr;

    u64 places = paramv[0];
    u64 NL = paramv[1];

    MyOcrTaskStruct_t TS_placeInit; _paramc = 3; _depc = 4;

    TS_placeInit.FNC = FNC_placeInit;
    ocrEdtTemplateCreate( &TS_placeInit.TML, TS_placeInit.FNC, _paramc, _depc );

    for( u64 p = 0; p < places; p++ )
    {
        u64 lo = (p * NL) / places;
        u64 hi = (((p + 1) * NL) / places) - 1;

        // More partitions than lookups leaves the tail of them empty.
        if( (((p + 1) * NL) / places) <= lo )
            continue;

        u64 place_paramv[3] = { p, lo, hi };
        ocrHint_t edtHNT;

        ocrEdtCreate( &TS_placeInit.EDT, TS_placeInit.TML,
                      EDT_PARAM_DEF, place_paramv, EDT_PARAM_DEF, NULL,
                      EDT_PROP_NONE, rsEdtAt(&edtHNT, p), NULL );

        _idep = 0;
        ocrAddDependence( DBK_InputsH, TS_placeInit.EDT, _idep++, DB_MODE_CONST );
        ocrAddDependence( DBK_dataH, TS_placeInit.EDT, _idep++, DB_MODE_CONST );
        ocrAddDependence( DBK_templatesH, TS_placeInit.EDT, _idep++, DB_MODE_CONST );
        ocrAddDependence( PTR_psumGuids[p], TS_placeInit.EDT, _idep++, DB_MODE_CONST );
    }

    return NULL_GUID;
}

