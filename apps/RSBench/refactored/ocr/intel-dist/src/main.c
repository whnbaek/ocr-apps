ocrGuid_t FNC_initSpawner(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    s32 _paramc, _depc, _idep;

    ocrGuid_t DBK_InputsH = depv[0].guid;

    Inputs *PTR_InputsH = depv[0].ptr;
    dataH_t *PTR_dataH = depv[1].ptr;
    rankTemplateH_t *PTR_templatesH = depv[2].ptr;

    int n_nuclides = PTR_InputsH->n_nuclides;
    int n_mats = PTR_InputsH->n_mats;

    _paramc = 5; _depc = EDT_PARAM_UNK;
    ocrEdtTemplateCreate( &(PTR_templatesH->TML_FNC_rankCompute), FNC_rankCompute, _paramc, _depc );
    _paramc = 4; _depc = 4;
    ocrEdtTemplateCreate( &(PTR_templatesH->TML_FNC_rankMultiLookupSpawner), FNC_rankMultiLookupSpawner, _paramc, _depc );
    _paramc = 1; _depc = EDT_PARAM_UNK;
    ocrEdtTemplateCreate( &(PTR_templatesH->TML_FNC_placeReduce), FNC_placeReduce, _paramc, _depc );
    _paramc = 2 + RS_GUID_PARAMS; _depc = 10;
    ocrEdtTemplateCreate( &(PTR_templatesH->TML_FNC_rankLookup), FNC_rankLookup, _paramc, _depc );
    _paramc = 3 + RS_GUID_PARAMS; _depc = 9;
    ocrEdtTemplateCreate( &(PTR_templatesH->TML_FNC_macroxs), FNC_macroxs, _paramc, _depc );
    _paramc = 3 + RS_GUID_PARAMS; _depc = EDT_PARAM_UNK;
    ocrEdtTemplateCreate( &(PTR_templatesH->TML_FNC_microxsAggregator), FNC_microxsAggregator, _paramc, _depc );

    int *PTR_nPoles_nuclide, *PTR_nWindows_nuclide, *PTR_numNucs_mat;
    ocrGuid_t *PTR_guids;
    ocrDbCreate( &(PTR_dataH->DBK_nPoles_nuclide), (void **) &PTR_nPoles_nuclide, sizeof(int)*(n_nuclides),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );
    ocrDbCreate( &(PTR_dataH->DBK_nWindows_nuclide), (void **) &PTR_nWindows_nuclide, sizeof(int)*(n_nuclides),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );
    ocrDbCreate( &(PTR_dataH->DBK_pole_DBguids_nuclide), (void **) &PTR_guids, sizeof(ocrGuid_t)*(n_nuclides),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );
    ocrDbCreate( &(PTR_dataH->DBK_window_DBguids_nuclide), (void **) &PTR_guids, sizeof(ocrGuid_t)*(n_nuclides),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );
    ocrDbCreate( &(PTR_dataH->DBK_pseudoK0RS_DBguids_nuclide), (void **) &PTR_guids, sizeof(ocrGuid_t)*(n_nuclides),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );
    ocrDbCreate( &(PTR_dataH->DBK_numNucs_mat), (void **) &PTR_numNucs_mat, sizeof(int)*(n_mats),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );
    ocrDbCreate( &(PTR_dataH->DBK_nuclideIDs_DBguids_mat), (void **) &PTR_guids, sizeof(ocrGuid_t)*(n_mats),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );
    ocrDbCreate( &(PTR_dataH->DBK_nuclideConcs_DBguids_mat), (void **) &PTR_guids, sizeof(ocrGuid_t)*(n_mats),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );

    ocrGuid_t TML_countGen, TML_nuclideGen, TML_materialGen, TML_initCollect;
    ocrEdtTemplateCreate( &TML_countGen, FNC_countGen, 0, 3 );
    ocrEdtTemplateCreate( &TML_nuclideGen, FNC_nuclideGen, 1, 4 );
    ocrEdtTemplateCreate( &TML_materialGen, FNC_materialGen, 1, 1 );
    ocrEdtTemplateCreate( &TML_initCollect, FNC_initCollect, 0, EDT_PARAM_UNK );

    /* The two count arrays are a histogram of one draw stream over the whole
     * nuclide index: a bin depends on every draw, so it cannot be produced
     * from the index of the thing that reads it.  One task builds both, and
     * the per-index producers consume them. */
    ocrGuid_t EVT_counts;
    ocrEventCreate( &EVT_counts, OCR_EVENT_STICKY_T, false );

    ocrGuid_t EDT_countGen, OET_countGen;
    ocrEdtCreate( &EDT_countGen, TML_countGen,
                  EDT_PARAM_DEF, NULL, EDT_PARAM_DEF, NULL,
                  EDT_PROP_NONE, NULL_HINT, &OET_countGen );

    ocrAddDependence( OET_countGen, EVT_counts, 0, DB_MODE_NULL );

    ocrGuid_t EDT_initCollect;
    ocrEdtCreate( &EDT_initCollect, TML_initCollect,
                  EDT_PARAM_DEF, NULL, 7 + n_nuclides + n_mats, NULL,
                  EDT_PROP_NONE, NULL_HINT, NULL );

    _idep = 0;
    ocrAddDependence( DBK_InputsH, EDT_initCollect, _idep++, DB_MODE_CONST );
    ocrAddDependence( PTR_dataH->DBK_pole_DBguids_nuclide, EDT_initCollect, _idep++, DB_MODE_RW );
    ocrAddDependence( PTR_dataH->DBK_window_DBguids_nuclide, EDT_initCollect, _idep++, DB_MODE_RW );
    ocrAddDependence( PTR_dataH->DBK_pseudoK0RS_DBguids_nuclide, EDT_initCollect, _idep++, DB_MODE_RW );
    ocrAddDependence( PTR_dataH->DBK_numNucs_mat, EDT_initCollect, _idep++, DB_MODE_RW );
    ocrAddDependence( PTR_dataH->DBK_nuclideIDs_DBguids_mat, EDT_initCollect, _idep++, DB_MODE_RW );
    ocrAddDependence( PTR_dataH->DBK_nuclideConcs_DBguids_mat, EDT_initCollect, _idep++, DB_MODE_RW );

    // The generator of index k runs on place k, so what it creates is homed
    // there: the dataset is sharded by the placement of its producers.
    for( int i = 0; i < n_nuclides; i++ )
    {
        u64 gen_paramv[1] = { (u64) i };
        ocrGuid_t EDT_gen, OET_gen;
        ocrHint_t edtHNT;
        u32 _gdep;

        ocrEdtCreate( &EDT_gen, TML_nuclideGen,
                      EDT_PARAM_DEF, gen_paramv, EDT_PARAM_DEF, NULL,
                      EDT_PROP_NONE, rsEdtAt(&edtHNT, (u64) i), &OET_gen );

        /* A task's output event is registered with its consumer before the
         * task's own last dependence is added, so the task cannot run — and
         * the event cannot fire — before the registration that carries it. */
        ocrAddDependence( OET_gen, EDT_initCollect, _idep++, DB_MODE_CONST );

        _gdep = 0;
        ocrAddDependence( DBK_InputsH, EDT_gen, _gdep++, DB_MODE_CONST );
        ocrAddDependence( PTR_dataH->DBK_nPoles_nuclide, EDT_gen, _gdep++, DB_MODE_CONST );
        ocrAddDependence( PTR_dataH->DBK_nWindows_nuclide, EDT_gen, _gdep++, DB_MODE_CONST );
        ocrAddDependence( EVT_counts, EDT_gen, _gdep++, DB_MODE_NULL );
    }

    for( int i = 0; i < n_mats; i++ )
    {
        u64 gen_paramv[1] = { (u64) i };
        ocrGuid_t EDT_gen, OET_gen;
        ocrHint_t edtHNT;

        ocrEdtCreate( &EDT_gen, TML_materialGen,
                      EDT_PARAM_DEF, gen_paramv, EDT_PARAM_DEF, NULL,
                      EDT_PROP_NONE, rsEdtAt(&edtHNT, (u64) (n_nuclides + i)), &OET_gen );

        ocrAddDependence( OET_gen, EDT_initCollect, _idep++, DB_MODE_CONST );
        ocrAddDependence( DBK_InputsH, EDT_gen, 0, DB_MODE_CONST );
    }

    ocrAddDependence( DBK_InputsH, EDT_countGen, 0, DB_MODE_CONST );
    ocrAddDependence( PTR_dataH->DBK_nPoles_nuclide, EDT_countGen, 1, DB_MODE_RW );
    ocrAddDependence( PTR_dataH->DBK_nWindows_nuclide, EDT_countGen, 2, DB_MODE_RW );

    return NULL_GUID;
}

