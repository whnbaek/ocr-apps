/* OCR implementation of RSBench with a distributed decomposition.
 *
 * The lookup range is split into a fixed number of partitions, each with its
 * own producer chain and its own sync batches, so no single task produces
 * work for the whole machine.  The cross-section dataset is sharded: nuclide
 * i is generated by, and therefore homed on, one place, and a lookup reaches
 * the nuclides of its material wherever they are.  Both the dataset and the
 * lookup results are summed into order-independent integer checksums.
 */

#include "ocr.h"
#include "rsbench.h"
#include "timers.h"

#ifndef MIN
#define MIN(x,y) ((x)<(y)?(x):(y))
#endif

