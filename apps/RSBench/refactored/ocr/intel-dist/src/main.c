ocrGuid_t FNC_globalInit(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    s32 _paramc, _depc, _idep;

    border_print();
    center_print("INITIALIZATION", 79);
    border_print();

    ocrGuid_t DBK_InputsH_0 = depv[0].guid;
    globalH_t* PTR_globalH = depv[1].ptr;

    Inputs* PTR_InputsH;
    ocrDbCreate( &(PTR_globalH->DBK_InputsH), (void **) &PTR_InputsH, sizeof(Inputs),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );

    ocrGuid_t TS_init_InputsH_OET;
    ocrEventCreate( &TS_init_InputsH_OET, OCR_EVENT_STICKY_T, false );

    MyOcrTaskStruct_t TS_init_InputsH; _paramc = 0; _depc = 2;

    TS_init_InputsH.FNC = FNC_init_InputsH;
    ocrEdtTemplateCreate( &TS_init_InputsH.TML, TS_init_InputsH.FNC, _paramc, _depc );

    ocrEdtCreate( &TS_init_InputsH.EDT, TS_init_InputsH.TML,
                  EDT_PARAM_DEF, NULL, EDT_PARAM_DEF, NULL,
                  EDT_PROP_NONE, NULL_HINT, &TS_init_InputsH.OET );

    ocrAddDependence( TS_init_InputsH.OET, TS_init_InputsH_OET, 0, DB_MODE_NULL );

    _idep = 0;
    ocrAddDependence( DBK_InputsH_0, TS_init_InputsH.EDT, _idep++, DB_MODE_CONST );
    ocrAddDependence( PTR_globalH->DBK_InputsH, TS_init_InputsH.EDT, _idep++, DB_MODE_RW );

    dataH_t* PTR_dataH;
    ocrDbCreate( &(PTR_globalH->DBK_dataH), (void **) &PTR_dataH, sizeof(dataH_t),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );

    rankTemplateH_t* PTR_templatesH;
    ocrDbCreate( &(PTR_globalH->DBK_templatesH), (void **) &PTR_templatesH, sizeof(rankTemplateH_t),
                 DB_PROP_NONE, NULL_HINT, NO_ALLOC );

    MyOcrTaskStruct_t TS_initSpawner; _paramc = 0; _depc = 4;

    TS_initSpawner.FNC = FNC_initSpawner;
    ocrEdtTemplateCreate( &TS_initSpawner.TML, TS_initSpawner.FNC, _paramc, _depc );

    ocrEdtCreate( &TS_initSpawner.EDT, TS_initSpawner.TML,
                  EDT_PARAM_DEF, NULL, EDT_PARAM_DEF, NULL,
                  EDT_PROP_NONE, NULL_HINT, NULL );

    _idep = 0;
    ocrAddDependence( PTR_globalH->DBK_InputsH, TS_initSpawner.EDT, _idep++, DB_MODE_CONST );
    ocrAddDependence( PTR_globalH->DBK_dataH, TS_initSpawner.EDT, _idep++, DB_MODE_RW );
    ocrAddDependence( PTR_globalH->DBK_templatesH, TS_initSpawner.EDT, _idep++, DB_MODE_RW );
    ocrAddDependence( TS_init_InputsH_OET, TS_initSpawner.EDT, _idep++, DB_MODE_NULL );

    return NULL_GUID;
}

