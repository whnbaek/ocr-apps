ocrGuid_t FNC_nuclideGen(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    Inputs *PTR_InputsH = depv[0].ptr;
    Inputs input = *PTR_InputsH;

    const int *PTR_nPoles_nuclide = depv[1].ptr;
    const int *PTR_nWindows_nuclide = depv[2].ptr;

    int i = (int) paramv[0];

    int n_poles = PTR_nPoles_nuclide[i];
    int n_windows = PTR_nWindows_nuclide[i];

    Pole* PTR_poles;
    Window* PTR_windows;
    double* PTR_pseudoK0RS;
    ocrHint_t dbHNT;

    ocrGuid_t DBK_poles, DBK_windows, DBK_pseudoK0RS, DBK_result;

    ocrDbCreate( &DBK_poles, (void **) &PTR_poles, sizeof(Pole)*(n_poles),
                 DB_PROP_NONE, rsDbHere(&dbHNT), NO_ALLOC );
    ocrDbCreate( &DBK_windows, (void **) &PTR_windows, sizeof(Window)*(n_windows),
                 DB_PROP_NONE, rsDbHere(&dbHNT), NO_ALLOC );
    ocrDbCreate( &DBK_pseudoK0RS, (void **) &PTR_pseudoK0RS, sizeof(double)*(input.numL),
                 DB_PROP_NONE, rsDbHere(&dbHNT), NO_ALLOC );

    unsigned long long cksum = generate_poles_i( input, i, n_poles, PTR_poles );
    generate_window_params_i( i, n_windows, n_poles, PTR_windows );
    generate_pseudo_K0RS_i( input, i, PTR_pseudoK0RS );

    nuclideResult_t* PTR_result;
    ocrDbCreate( &DBK_result, (void **) &PTR_result, sizeof(nuclideResult_t),
                 DB_PROP_NONE, rsDbHere(&dbHNT), NO_ALLOC );

    PTR_result->DBK_poles = DBK_poles;
    PTR_result->DBK_windows = DBK_windows;
    PTR_result->DBK_pseudoK0RS = DBK_pseudoK0RS;
    PTR_result->cksum = cksum;

    return DBK_result;
}

