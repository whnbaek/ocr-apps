/* Distributed decomposition of the OCR XSBench lookup kernel.
 *
 * The lookup range is cut into `places`.  A place owns a contiguous share of
 * the lookups, one producer over that share, and its own replica of the
 * physics table (nuclide grids, unionized energy grid, the per-gridpoint
 * nuclide index plane, material tables) -- every object of a place is created
 * at one policy domain, derived from the place index.  A lookup is still a
 * three-task chain (lookup, macroxs, aggregator) with the same dependence
 * count per lookup, so the runtime work per lookup is what it was; what
 * changes is that no chain reaches across a policy domain and that production
 * is as wide as the number of places rather than one task for the machine.
 *
 * The table is generated by the tasks that own it from an index-seeded
 * generator, so replicas agree without exchanging anything and the instance
 * does not depend on the number of places or nodes.  Each lookup quantizes its
 * macroscopic cross section into an integer digest accumulated per place and
 * summed once at the end, so the verification value is a function of the
 * lookup results and is invariant under partitioning and completion order.
 */

#include "ocr.h"
#include <extensions/ocr-affinity.h>

#include "XSbench_header.h"
#include "timers.h"

#ifndef MIN
#define MIN(x,y) ((x)<(y)?(x):(y))
#endif

#define PARAMC(T) ((u32)((sizeof(T) + sizeof(u64) - 1) / sizeof(u64)))

/* Everything a task of one place needs: the run parameters and the handles of
 * that place's replica.  It is the only block the compute chain acquires that
 * is not itself part of the replica, so no task of any place ever reads an
 * object of another. */
typedef struct
{
    Inputs in;
    ocrGuid_t DBK_nuclideGuids;   // ocrGuid_t[n_isotopes]
    ocrGuid_t DBK_uEnergy;        // double[U]
    ocrGuid_t DBK_blockGuids;     // ocrGuid_t[nblocks]
    ocrGuid_t DBK_matNumNucs;     // int[n_mats]
    ocrGuid_t DBK_matIndexGuids;  // ocrGuid_t[n_mats]
    ocrGuid_t DBK_matConcGuids;   // ocrGuid_t[n_mats]
    ocrGuid_t DBK_shardGuids;     // ocrGuid_t[batch]
    ocrGuid_t DBK_digest;         // u64
    ocrGuid_t TML_lookup;
    ocrGuid_t TML_macroxs;
    ocrGuid_t TML_aggregator;
    ocrGuid_t TML_placeCompute;
    ocrGuid_t TML_placeBatch;
    ocrGuid_t TML_placeFinalize;
    s64 nblocks;
    s64 blockLen;
    /* The affinity of a place is a constant of the place: the hints are built
     * once, so no create site re-derives them. */
    ocrHint_t edtHNT;
    ocrHint_t dbHNT;
    u8 hinted;
} placeH_t;

typedef struct { u64 place; ocrGuid_t reduceEDT; } placePrm_t;
typedef struct { u64 place; u64 hi; u64 cursor; ocrGuid_t reduceEDT; } computePrm_t;
typedef struct { u64 place; u64 ilookup; ocrGuid_t shard; } lookupPrm_t;
typedef struct
{
    u64 place;
    u64 ilookup;
    u64 energyBits;
    u64 mat;
    u64 num_nucs;
    u64 row;
    ocrGuid_t shard;
} chainPrm_t;

