ocrGuid_t FNC_lookup(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    ocrGuid_t DBK_placeH = depv[0].guid;
    ocrGuid_t DBK_nuclideGuids = depv[1].guid;

    placeH_t* PTR_placeH = depv[0].ptr;
    double* PTR_uEnergy = depv[2].ptr;
    ocrGuid_t* PTR_blockGuids = depv[3].ptr;
    int* PTR_matNumNucs = depv[4].ptr;
    ocrGuid_t* PTR_matIndexGuids = depv[5].ptr;
    ocrGuid_t* PTR_matConcGuids = depv[6].ptr;

    lookupPrm_t* PTR_prm = (lookupPrm_t*) paramv;
    u64 place = PTR_prm->place;
    u64 ilookup = PTR_prm->ilookup;

    s64 n_isotopes = PTR_placeH->in.n_isotopes;
    s64 n_gridpoints = PTR_placeH->in.n_gridpoints;
    s64 blockLen = PTR_placeH->blockLen;

    unsigned long seed = (ilookup+1)*19+17;

    double p_energy = rn(&seed);
    int mat = pick_mat(&seed);

    long idx = grid_search_double( n_isotopes * n_gridpoints, p_energy, PTR_uEnergy );

    s64 blk = idx / blockLen;
    s64 row = idx - blk * blockLen;

    chainPrm_t prm;
    prm.place = place;
    prm.ilookup = ilookup;
    memcpy( &prm.energyBits, &p_energy, sizeof(prm.energyBits) );
    prm.mat = (u64) mat;
    prm.num_nucs = (u64) PTR_matNumNucs[mat];
    prm.row = (u64) row;
    prm.shard = PTR_prm->shard;

    ocrHint_t edtHNT;
    ocrGuid_t EDT_macroxs;
    ocrEdtCreate( &EDT_macroxs, PTR_placeH->TML_macroxs,
                  EDT_PARAM_DEF, (u64*) &prm, EDT_PARAM_DEF, NULL,
                  EDT_PROP_NONE, placeEdtHintOf(&edtHNT, PTR_placeH), NULL );

    ocrAddDependence( DBK_placeH, EDT_macroxs, 0, DB_MODE_CONST );
    ocrAddDependence( DBK_nuclideGuids, EDT_macroxs, 1, DB_MODE_CONST );
    ocrAddDependence( PTR_blockGuids[blk], EDT_macroxs, 2, DB_MODE_CONST );
    ocrAddDependence( PTR_matIndexGuids[mat], EDT_macroxs, 3, DB_MODE_CONST );
    ocrAddDependence( PTR_matConcGuids[mat], EDT_macroxs, 4, DB_MODE_CONST );

    return NULL_GUID;
}

