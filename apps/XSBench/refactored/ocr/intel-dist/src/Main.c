/* A place's objects all live at one policy domain, derived from the place
 * index alone, so every task computes the same map without consulting any
 * shared state.  A single-domain run needs no hint at all. */
static ocrHint_t * placeEdtHint( ocrHint_t *h, u64 place )
{
    u64 pdCount;
    ocrAffinityCount( AFFINITY_PD, &pdCount );
    if( pdCount <= 1 ) return NULL_HINT;
    ocrGuid_t aff;
    ocrAffinityGetAt( AFFINITY_PD, place % pdCount, &aff );
    ocrHintInit( h, OCR_HINT_EDT_T );
    ocrSetHintValue( h, OCR_HINT_EDT_AFFINITY, ocrAffinityToHintValue(aff) );
    return h;
}

static ocrHint_t * placeDbHint( ocrHint_t *h, u64 place )
{
    u64 pdCount;
    ocrAffinityCount( AFFINITY_PD, &pdCount );
    if( pdCount <= 1 ) return NULL_HINT;
    ocrGuid_t aff;
    ocrAffinityGetAt( AFFINITY_PD, place % pdCount, &aff );
    ocrHintInit( h, OCR_HINT_DB_T );
    ocrSetHintValue( h, OCR_HINT_DB_AFFINITY, ocrAffinityToHintValue(aff) );
    return h;
}

/* A hint is a value, so a task that already holds its place's handle copies
 * the prebuilt one instead of asking the runtime for the affinity again. */
static ocrHint_t * placeEdtHintOf( ocrHint_t *h, const placeH_t *ph )
{
    if( !ph->hinted ) return NULL_HINT;
    *h = ph->edtHNT;
    return h;
}

static ocrHint_t * placeDbHintOf( ocrHint_t *h, const placeH_t *ph )
{
    if( !ph->hinted ) return NULL_HINT;
    *h = ph->dbHNT;
    return h;
}

/* Block partition of [0,n) into `parts`: part p owns [lo,hi). */
static void partition_range( u64 n, u64 parts, u64 p, u64 *lo, u64 *hi )
{
    u64 q = n / parts;
    u64 r = n % parts;
    *lo = p * q + ( p < r ? p : r );
    *hi = *lo + q + ( p < r ? 1 : 0 );
}

ocrGuid_t FNC_placeSpawner(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    ocrGuid_t DBK_Inputs = depv[0].guid;
    Inputs* PTR_Inputs = depv[0].ptr;
    placePrm_t* PTR_prm = (placePrm_t*) paramv;

    u64 places = (u64) PTR_Inputs->places;

    ocrGuid_t TML_placeInit;
    ocrEdtTemplateCreate( &TML_placeInit, FNC_placeInit, PARAMC(placePrm_t), 2 );

    for( u64 p = 0; p < places; p++ )
    {
        ocrHint_t dbHNT, edtHNT;

        ocrGuid_t DBK_placeH;
        placeH_t* PTR_placeH;
        ocrDbCreate( &DBK_placeH, (void**) &PTR_placeH, sizeof(placeH_t),
                     DB_PROP_NONE, placeDbHint(&dbHNT, p), NO_ALLOC );

        placePrm_t prm;
        prm.place = p;
        prm.reduceEDT = PTR_prm->reduceEDT;

        ocrGuid_t EDT_placeInit;
        ocrEdtCreate( &EDT_placeInit, TML_placeInit,
                      EDT_PARAM_DEF, (u64*) &prm, EDT_PARAM_DEF, NULL,
                      EDT_PROP_NONE, placeEdtHint(&edtHNT, p), NULL );

        /* Release precedes any exposure of the block. */
        ocrDbRelease( DBK_placeH );
        ocrAddDependence( DBK_Inputs, EDT_placeInit, 0, DB_MODE_CONST );
        ocrAddDependence( DBK_placeH, EDT_placeInit, 1, DB_MODE_RW );
    }

    return NULL_GUID;
}

ocrGuid_t FNC_placeInit(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    ocrGuid_t DBK_placeH = depv[1].guid;

    Inputs* PTR_Inputs = depv[0].ptr;
    placeH_t* PTR_placeH = depv[1].ptr;

    placePrm_t* PTR_prm = (placePrm_t*) paramv;
    u64 place = PTR_prm->place;

    memcpy( &PTR_placeH->in, PTR_Inputs, sizeof(Inputs) );

    /* Derive the place's affinity once; a single-domain run needs no hint at
     * all. */
    PTR_placeH->hinted = 0;
    {
        u64 pdCount;
        ocrAffinityCount( AFFINITY_PD, &pdCount );
        if( pdCount > 1 )
        {
            ocrGuid_t aff;
            ocrAffinityGetAt( AFFINITY_PD, place % pdCount, &aff );
            ocrHintInit( &PTR_placeH->edtHNT, OCR_HINT_EDT_T );
            ocrSetHintValue( &PTR_placeH->edtHNT, OCR_HINT_EDT_AFFINITY,
                             ocrAffinityToHintValue(aff) );
            ocrHintInit( &PTR_placeH->dbHNT, OCR_HINT_DB_T );
            ocrSetHintValue( &PTR_placeH->dbHNT, OCR_HINT_DB_AFFINITY,
                             ocrAffinityToHintValue(aff) );
            PTR_placeH->hinted = 1;
        }
    }

    s64 n_isotopes = PTR_Inputs->n_isotopes;
    s64 n_gridpoints = PTR_Inputs->n_gridpoints;
    s64 n_mats = PTR_Inputs->n_mats;
    s64 batch = PTR_Inputs->batch;
    s64 U = n_isotopes * n_gridpoints;

    /* One block of the index plane per in-flight lookup slot, so the alignment
     * phase is at most as wide as the compute phase it feeds -- rounding the
     * block length up can cover the plane in fewer blocks than slots. */
    s64 nblocks = MIN( batch, U );
    s64 blockLen = ( U + nblocks - 1 ) / nblocks;
    nblocks = ( U + blockLen - 1 ) / blockLen;

    PTR_placeH->nblocks = nblocks;
    PTR_placeH->blockLen = blockLen;

    ocrHint_t dbHNT, edtHNT;
    s64 i;

    ocrGuid_t* PTR_nuclideGuids;
    ocrDbCreate( &PTR_placeH->DBK_nuclideGuids, (void**) &PTR_nuclideGuids,
                 sizeof(ocrGuid_t)*n_isotopes, DB_PROP_NONE, placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
    for( i = 0; i < n_isotopes; i++ )
    {
        NuclideGridPoint* PTR_grid;
        ocrDbCreate( &PTR_nuclideGuids[i], (void**) &PTR_grid,
                     sizeof(NuclideGridPoint)*n_gridpoints, DB_PROP_NONE,
                     placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
        ocrDbRelease( PTR_nuclideGuids[i] );
    }

    double* PTR_uEnergy;
    ocrDbCreate( &PTR_placeH->DBK_uEnergy, (void**) &PTR_uEnergy, sizeof(double)*U,
                 DB_PROP_NONE, placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
    ocrDbRelease( PTR_placeH->DBK_uEnergy );

    ocrGuid_t* PTR_blockGuids;
    ocrDbCreate( &PTR_placeH->DBK_blockGuids, (void**) &PTR_blockGuids,
                 sizeof(ocrGuid_t)*nblocks, DB_PROP_NONE, placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
    for( i = 0; i < nblocks; i++ )
    {
        int* PTR_block;
        ocrDbCreate( &PTR_blockGuids[i], (void**) &PTR_block,
                     sizeof(int)*blockLen*n_isotopes, DB_PROP_NONE,
                     placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
        ocrDbRelease( PTR_blockGuids[i] );
    }

    int* PTR_matNumNucs;
    ocrDbCreate( &PTR_placeH->DBK_matNumNucs, (void**) &PTR_matNumNucs, sizeof(int)*n_mats,
                 DB_PROP_NONE, placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
    ocrDbRelease( PTR_placeH->DBK_matNumNucs );

    ocrGuid_t* PTR_matIndexGuids;
    ocrDbCreate( &PTR_placeH->DBK_matIndexGuids, (void**) &PTR_matIndexGuids,
                 sizeof(ocrGuid_t)*n_mats, DB_PROP_NONE, placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
    ocrDbRelease( PTR_placeH->DBK_matIndexGuids );

    ocrGuid_t* PTR_matConcGuids;
    ocrDbCreate( &PTR_placeH->DBK_matConcGuids, (void**) &PTR_matConcGuids,
                 sizeof(ocrGuid_t)*n_mats, DB_PROP_NONE, placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
    ocrDbRelease( PTR_placeH->DBK_matConcGuids );

    /* One accumulator per in-flight slot: within a batch a slot is written by
     * exactly one chain, and batches do not overlap, so the accumulation needs
     * no atomic and contends with nothing. */
    ocrGuid_t* PTR_shardGuids;
    ocrDbCreate( &PTR_placeH->DBK_shardGuids, (void**) &PTR_shardGuids,
                 sizeof(ocrGuid_t)*batch, DB_PROP_NONE, placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
    for( i = 0; i < batch; i++ )
    {
        u64* PTR_shard;
        ocrDbCreate( &PTR_shardGuids[i], (void**) &PTR_shard, sizeof(u64),
                     DB_PROP_NONE, placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
        *PTR_shard = 0;
        ocrDbRelease( PTR_shardGuids[i] );
    }

    u64* PTR_digest;
    ocrDbCreate( &PTR_placeH->DBK_digest, (void**) &PTR_digest, sizeof(u64),
                 DB_PROP_NONE, placeDbHintOf(&dbHNT, PTR_placeH), NO_ALLOC );
    *PTR_digest = 0;
    ocrDbRelease( PTR_placeH->DBK_digest );

    ocrEdtTemplateCreate( &PTR_placeH->TML_lookup, FNC_lookup, PARAMC(lookupPrm_t), 7 );
    ocrEdtTemplateCreate( &PTR_placeH->TML_macroxs, FNC_macroxs, PARAMC(chainPrm_t), 5 );
    ocrEdtTemplateCreate( &PTR_placeH->TML_aggregator, FNC_aggregator, PARAMC(chainPrm_t),
                          EDT_PARAM_UNK );
    ocrEdtTemplateCreate( &PTR_placeH->TML_placeCompute, FNC_placeCompute,
                          PARAMC(computePrm_t), 4 );
    ocrEdtTemplateCreate( &PTR_placeH->TML_placeBatch, FNC_placeBatch, 3, 2 );
    ocrEdtTemplateCreate( &PTR_placeH->TML_placeFinalize, FNC_placeFinalize,
                          PARAMC(placePrm_t), (u32)(3 + batch) );

    ocrGuid_t DBK_nuclideGuidsK = PTR_placeH->DBK_nuclideGuids;
    ocrGuid_t DBK_blockGuidsK = PTR_placeH->DBK_blockGuids;
    ocrGuid_t DBK_matNumNucsK = PTR_placeH->DBK_matNumNucs;
    ocrGuid_t DBK_matIndexGuidsK = PTR_placeH->DBK_matIndexGuids;
    ocrGuid_t DBK_matConcGuidsK = PTR_placeH->DBK_matConcGuids;
    ocrGuid_t DBK_shardGuidsK = PTR_placeH->DBK_shardGuids;
    ocrGuid_t TML_placeComputeK = PTR_placeH->TML_placeCompute;

    u64 spawn_paramv[1] = { place };

    ocrGuid_t EVT_grid, EVT_ueg, EVT_align, EVT_mat;
    ocrEventCreate( &EVT_grid, OCR_EVENT_STICKY_T, false );
    ocrEventCreate( &EVT_ueg, OCR_EVENT_STICKY_T, false );
    ocrEventCreate( &EVT_align, OCR_EVENT_STICKY_T, false );
    ocrEventCreate( &EVT_mat, OCR_EVENT_STICKY_T, false );

    /* The generators, the union build and the alignment are separate spawn
     * scopes rather than one wired graph: a reader's dependence on a block is
     * registered by the task that spawns it, which runs only once the block's
     * writer has finished and released. */
    ocrGuid_t TML_gridSpawner, EDT_gridSpawner, OET_gridSpawner;
    ocrEdtTemplateCreate( &TML_gridSpawner, FNC_gridSpawner, 1, 2 );
    ocrEdtCreate( &EDT_gridSpawner, TML_gridSpawner,
                  EDT_PARAM_DEF, spawn_paramv, EDT_PARAM_DEF, NULL,
                  EDT_PROP_FINISH, placeEdtHintOf(&edtHNT, PTR_placeH), &OET_gridSpawner );
    ocrAddDependence( OET_gridSpawner, EVT_grid, 0, DB_MODE_NULL );

    ocrGuid_t TML_uegSpawner, EDT_uegSpawner, OET_uegSpawner;
    ocrEdtTemplateCreate( &TML_uegSpawner, FNC_uegSpawner, 1, 3 );
    ocrEdtCreate( &EDT_uegSpawner, TML_uegSpawner,
                  EDT_PARAM_DEF, spawn_paramv, EDT_PARAM_DEF, NULL,
                  EDT_PROP_FINISH, placeEdtHintOf(&edtHNT, PTR_placeH), &OET_uegSpawner );
    ocrAddDependence( OET_uegSpawner, EVT_ueg, 0, DB_MODE_NULL );

    ocrGuid_t TML_alignSpawner, EDT_alignSpawner, OET_alignSpawner;
    ocrEdtTemplateCreate( &TML_alignSpawner, FNC_alignSpawner, 1, 4 );
    ocrEdtCreate( &EDT_alignSpawner, TML_alignSpawner,
                  EDT_PARAM_DEF, spawn_paramv, EDT_PARAM_DEF, NULL,
                  EDT_PROP_FINISH, placeEdtHintOf(&edtHNT, PTR_placeH), &OET_alignSpawner );
    ocrAddDependence( OET_alignSpawner, EVT_align, 0, DB_MODE_NULL );

    ocrGuid_t TML_matInit, EDT_matInit, OET_matInit;
    ocrEdtTemplateCreate( &TML_matInit, FNC_matInit, 1, 4 );
    ocrEdtCreate( &EDT_matInit, TML_matInit,
                  EDT_PARAM_DEF, spawn_paramv, EDT_PARAM_DEF, NULL,
                  EDT_PROP_NONE, placeEdtHintOf(&edtHNT, PTR_placeH), &OET_matInit );
    ocrAddDependence( OET_matInit, EVT_mat, 0, DB_MODE_NULL );

    u64 lo, hi;
    partition_range( (u64) PTR_Inputs->lookups, (u64) PTR_Inputs->places, place, &lo, &hi );

    computePrm_t cprm;
    cprm.place = place;
    cprm.hi = ( hi > lo ) ? hi - 1 : lo;
    cprm.cursor = ( hi > lo ) ? lo : lo + 1;
    cprm.reduceEDT = PTR_prm->reduceEDT;

    ocrGuid_t EDT_placeCompute;
    ocrEdtCreate( &EDT_placeCompute, TML_placeComputeK,
                  EDT_PARAM_DEF, (u64*) &cprm, EDT_PARAM_DEF, NULL,
                  EDT_PROP_NONE, placeEdtHintOf(&edtHNT, PTR_placeH), NULL );

    /* Release precedes any exposure of the block. */
    ocrDbRelease( DBK_nuclideGuidsK );
    ocrDbRelease( DBK_blockGuidsK );
    ocrDbRelease( DBK_shardGuidsK );
    ocrDbRelease( DBK_placeH );

    ocrAddDependence( DBK_placeH, EDT_gridSpawner, 0, DB_MODE_CONST );
    ocrAddDependence( DBK_nuclideGuidsK, EDT_gridSpawner, 1, DB_MODE_CONST );

    ocrAddDependence( DBK_placeH, EDT_uegSpawner, 0, DB_MODE_CONST );
    ocrAddDependence( DBK_nuclideGuidsK, EDT_uegSpawner, 1, DB_MODE_CONST );
    ocrAddDependence( EVT_grid, EDT_uegSpawner, 2, DB_MODE_NULL );

    ocrAddDependence( DBK_placeH, EDT_alignSpawner, 0, DB_MODE_CONST );
    ocrAddDependence( DBK_nuclideGuidsK, EDT_alignSpawner, 1, DB_MODE_CONST );
    ocrAddDependence( DBK_blockGuidsK, EDT_alignSpawner, 2, DB_MODE_CONST );
    ocrAddDependence( EVT_ueg, EDT_alignSpawner, 3, DB_MODE_NULL );

    ocrAddDependence( DBK_placeH, EDT_matInit, 0, DB_MODE_CONST );
    ocrAddDependence( DBK_matNumNucsK, EDT_matInit, 1, DB_MODE_RW );
    ocrAddDependence( DBK_matIndexGuidsK, EDT_matInit, 2, DB_MODE_RW );
    ocrAddDependence( DBK_matConcGuidsK, EDT_matInit, 3, DB_MODE_RW );

    ocrAddDependence( DBK_placeH, EDT_placeCompute, 0, DB_MODE_CONST );
    ocrAddDependence( DBK_shardGuidsK, EDT_placeCompute, 1, DB_MODE_CONST );
    ocrAddDependence( EVT_align, EDT_placeCompute, 2, DB_MODE_NULL );
    ocrAddDependence( EVT_mat, EDT_placeCompute, 3, DB_MODE_NULL );

    return NULL_GUID;
}

ocrGuid_t FNC_gridSpawner(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    ocrGuid_t DBK_placeH = depv[0].guid;

    placeH_t* PTR_placeH = depv[0].ptr;
    ocrGuid_t* PTR_nuclideGuids = depv[1].ptr;

    s64 n_isotopes = PTR_placeH->in.n_isotopes;
    s64 j;

    ocrGuid_t TML_gridGen;
    ocrEdtTemplateCreate( &TML_gridGen, FNC_gridGen, 1, 2 );

    for( j = 0; j < n_isotopes; j++ )
    {
        ocrHint_t edtHNT;
        u64 gen_paramv[1] = { (u64) j };
        ocrGuid_t EDT_gridGen;
        ocrEdtCreate( &EDT_gridGen, TML_gridGen,
                      EDT_PARAM_DEF, gen_paramv, EDT_PARAM_DEF, NULL,
                      EDT_PROP_NONE, placeEdtHintOf(&edtHNT, PTR_placeH), NULL );

        ocrAddDependence( DBK_placeH, EDT_gridGen, 0, DB_MODE_CONST );
        ocrAddDependence( PTR_nuclideGuids[j], EDT_gridGen, 1, DB_MODE_RW );
    }

    return NULL_GUID;
}

ocrGuid_t FNC_gridGen(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    placeH_t* PTR_placeH = depv[0].ptr;
    NuclideGridPoint* PTR_grid = depv[1].ptr;

    s64 j = (s64) paramv[0];
    s64 n_gridpoints = PTR_placeH->in.n_gridpoints;
    s64 k;

    for( k = 0; k < n_gridpoints; k++ )
    {
        PTR_grid[k].energy        = rn_indexed( XS_STREAM_GRID, xs_grid_index(j, k, n_gridpoints, 0) );
        PTR_grid[k].total_xs      = rn_indexed( XS_STREAM_GRID, xs_grid_index(j, k, n_gridpoints, 1) );
        PTR_grid[k].elastic_xs    = rn_indexed( XS_STREAM_GRID, xs_grid_index(j, k, n_gridpoints, 2) );
        PTR_grid[k].absorbtion_xs = rn_indexed( XS_STREAM_GRID, xs_grid_index(j, k, n_gridpoints, 3) );
        PTR_grid[k].fission_xs    = rn_indexed( XS_STREAM_GRID, xs_grid_index(j, k, n_gridpoints, 4) );
        PTR_grid[k].nu_fission_xs = rn_indexed( XS_STREAM_GRID, xs_grid_index(j, k, n_gridpoints, 5) );
    }

    qsort( PTR_grid, n_gridpoints, sizeof(NuclideGridPoint), NGP_compare );

    return NULL_GUID;
}

ocrGuid_t FNC_uegSpawner(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    ocrGuid_t DBK_placeH = depv[0].guid;

    placeH_t* PTR_placeH = depv[0].ptr;
    ocrGuid_t* PTR_nuclideGuids = depv[1].ptr;

    s64 n_isotopes = PTR_placeH->in.n_isotopes;
    s64 i;

    ocrHint_t edtHNT;
    ocrGuid_t TML_uegBuild, EDT_uegBuild;
    ocrEdtTemplateCreate( &TML_uegBuild, FNC_uegBuild, 1, (u32)(2 + n_isotopes) );
    ocrEdtCreate( &EDT_uegBuild, TML_uegBuild,
                  EDT_PARAM_DEF, paramv, EDT_PARAM_DEF, NULL,
                  EDT_PROP_NONE, placeEdtHintOf(&edtHNT, PTR_placeH), NULL );

    ocrAddDependence( DBK_placeH, EDT_uegBuild, 0, DB_MODE_CONST );
    ocrAddDependence( PTR_placeH->DBK_uEnergy, EDT_uegBuild, 1, DB_MODE_RW );
    for( i = 0; i < n_isotopes; i++ )
        ocrAddDependence( PTR_nuclideGuids[i], EDT_uegBuild, (u32)(2 + i), DB_MODE_CONST );

    return NULL_GUID;
}

ocrGuid_t FNC_uegBuild(u32 paramc, u64* paramv, u32 depc, ocrEdtDep_t depv[])
{
    placeH_t* PTR_placeH = depv[0].ptr;
    double* PTR_uEnergy = depv[1].ptr;

    s64 n_isotopes = PTR_placeH->in.n_isotopes;
    s64 n_gridpoints = PTR_placeH->in.n_gridpoints;
    s64 i, j;

    for( i = 0; i < n_isotopes; i++ )
    {
        NuclideGridPoint* PTR_grid = depv[2 + i].ptr;
        for( j = 0; j < n_gridpoints; j++ )
            PTR_uEnergy[i*n_gridpoints + j] = PTR_grid[j].energy;
    }

    qsort( PTR_uEnergy, n_isotopes*n_gridpoints, sizeof(double), double_compare );

    /* The table is a pure function of the arguments, so every replica holds
     * the same values and one of them is the whole answer.  The sum is over
     * bit patterns and is therefore exact and order-independent; it verifies
     * the generated table, not the lookup arithmetic. */
    if( paramv[0] == 0 )
    {
        ocrPrintf("XSBench grid checksum: %llu\n",
                  xs_grid_checksum( PTR_uEnergy, (long) n_isotopes * (long) n_gridpoints ));
    }

    return NULL_GUID;
}

